/**
 * Generate test media for test-vault/Media with speech synthesis (espeak-ng) and ffmpeg, plus
 * transcripts whose timings match it:
 *   Loomings.webm + Loomings.srt                    (audio only, same name, no duration in the header)
 *   Lecture.mp4 + Lecture.en.vtt                   (video, language suffix, speakers)
 *   bun scripts/fixtures.ts
 */
import { $ } from 'bun';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const out = join(import.meta.dir, '../test-vault/Media');
const tmp = mkdtempSync(join(tmpdir(), 'tpp-fixtures-'));

const loomings = [
	'Call me Ishmael.',
	'Some years ago, never mind how long precisely, having little or no money in my purse,',
	'and nothing particular to interest me on shore,',
	'I thought I would sail about a little and see the watery part of the world.',
	'It is a way I have of driving off the spleen and regulating the circulation.',
	'Whenever I find myself growing grim about the mouth;',
	'whenever it is a damp, drizzly November in my soul;',
	'then, I account it high time to get to sea as soon as I can.',
	'This is my substitute for pistol and ball.',
	'There is nothing surprising in this.',
];
const lecture: [string, string][] = [
	['Ada', 'Welcome to the lecture on whales.'],
	['Ada', 'Today we look at the sperm whale and its habits.'],
	['Bert', 'Is it true that they dive very deep?'],
	['Ada', 'Yes, more than a thousand meters, and for over an hour.'],
	['Bert', 'That is remarkable.'],
];

/** Speak each line to a wav; return the cue times (with a pause between lines). */
async function speak(name: string, lines: string[], voice: string, gap = 0.6): Promise<{ start: number; end: number }[]> {
	const parts: string[] = [];
	const times: { start: number; end: number }[] = [];
	let t = 0.3;
	await $`ffmpeg -loglevel error -f lavfi -i anullsrc=r=22050:cl=mono -t 0.3 ${join(tmp, `${name}-pad.wav`)}`;
	parts.push(join(tmp, `${name}-pad.wav`));
	for (const [i, line] of lines.entries()) {
		const wav = join(tmp, `${name}-${i}.wav`);
		await $`espeak-ng -v ${voice} -s 150 -w ${wav} ${line}`.quiet();
		const d = Number((await $`ffprobe -v error -show_entries format=duration -of csv=p=0 ${wav}`.text()).trim());
		times.push({ start: t, end: t + d });
		parts.push(wav);
		const pause = join(tmp, `${name}-gap-${i}.wav`);
		await $`ffmpeg -loglevel error -f lavfi -i anullsrc=r=22050:cl=mono -t ${gap} ${pause}`;
		parts.push(pause);
		t += d + gap;
	}
	writeFileSync(join(tmp, `${name}.txt`), parts.map((p) => `file '${p}'`).join('\n'));
	await $`ffmpeg -loglevel error -f concat -safe 0 -i ${join(tmp, `${name}.txt`)} -c pcm_s16le ${join(tmp, `${name}.wav`)}`;
	return times;
}

const clock = (t: number, sep: string, hours = true) => {
	const ms = Math.round(t * 1000);
	const h = Math.floor(ms / 3600000);
	const m = Math.floor((ms % 3600000) / 60000);
	const s = Math.floor((ms % 60000) / 1000);
	const pad = (n: number, w = 2) => String(n).padStart(w, '0');
	return `${hours ? `${pad(h)}:` : ''}${pad(m)}:${pad(s)}${sep}${pad(ms % 1000, 3)}`;
};

const lt = await speak('loomings', loomings, 'en-us');
// Written to a pipe, like a browser's MediaRecorder: the WebM header has no duration.
await $`ffmpeg -loglevel error -y -i ${join(tmp, 'loomings.wav')} -c:a libopus -b:a 32k -f webm pipe:1 > ${join(out, 'Loomings.webm')}`;
writeFileSync(join(out, 'Loomings.srt'), lt.map((c, i) => `${i + 1}\n${clock(c.start, ',')} --> ${clock(c.end, ',')}\n${loomings[i]}\n`).join('\n'));

const vt = await speak('lecture', lecture.map(([, l]) => l), 'en-gb');
const dur = vt[vt.length - 1].end + 0.6;
await $`ffmpeg -loglevel error -y -f lavfi -i testsrc=size=640x360:rate=15:duration=${dur} -i ${join(tmp, 'lecture.wav')} -c:v libx264 -pix_fmt yuv420p -preset veryfast -c:a aac -shortest ${join(out, 'Lecture.mp4')}`;
writeFileSync(
	join(out, 'Lecture.en.vtt'),
	`WEBVTT\n\nNOTE Generated by scripts/fixtures.ts\n\n${vt.map((c, i) => `cue-${i + 1}\n${clock(c.start, '.', false)} --> ${clock(c.end, '.', false)}\n<v ${lecture[i][0]}>${lecture[i][1]}`).join('\n\n')}\n`,
);
console.log(`wrote ${out}: Loomings.webm/.srt, Lecture.mp4/.en.vtt`);
